/**
 * Project gallery modal (mockups cran_7): saved models from IndexedDB
 * (idb-keyval) plus four parametric templates — Treillis Warren 24 m,
 * Portique industriel, Potence encastrée, Poutre continue.
 *
 * v1.6.0: the templates are generated by the PURE-RUST parametric
 * generator (`rdm-cad::parametric` through `generate_parametric_structure`)
 * with configurable Portée L / Hauteur H / Travées / Profilés, and the
 * modal doubles as the header project menu's `Exporter (.rdm)` surface.
 */
const GALLERY_KEY = "rdm-projects";

export interface GalleryEntry {
  id: string;
  name: string;
  savedAt: string;
  project: ProjectData;
}

export async function saveToGallery(project: ProjectData): Promise<void> {
  const list = (await get<GalleryEntry[]>(GALLERY_KEY)) ?? [];
  const entry: GalleryEntry = {
    id: `${Date.now()}`,
    name: project.name,
    savedAt: new Date().toISOString(),
    project,
  };
  await set(GALLERY_KEY, [entry, ...list].slice(0, 12));
}

/** Parametric template builders (SI units, simply supported layouts). */
export function buildTemplate(kind: string): ProjectData {
  const node = (id: number, x: number, y: number, z: number) => ({ id, x, y, z });
  const beam = (id: number, n1: number, n2: number) => ({
    id,
    n1,
    n2,
    section_id: "IPE 200",
    material_id: "S235JR",
    roll_angle_rad: 0,
    releases_start: [false, false, false, false, false, false],
    releases_end: [false, false, false, false, false, false],
    k_buckling_y: 1,
    k_buckling_z: 1,
  });
  const support = (nodeId: number, locked: boolean[]) => ({
    node_id: nodeId,
    locked_dofs: locked,
    spring_stiffness: [0, 0, 0, 0, 0, 0],
  });
  const load = (nodeId: number, fz: number) => ({
    case: "Permanent" as const,
    kind: "Nodal" as const,
    node_id: nodeId,
    forces: { fx: 0, fy: 0, fz, mx: 0, my: 0, mz: 0 },
  });
  const base = {
    version: 1,
    structure: {
      supports: [] as ReturnType<typeof support>[],
      loads: [] as ReturnType<typeof load>[],
      self_weight_enabled: true,
      sections: {},
      materials: {},
    },
    selection: { nodeId: null, beamId: null },
  };
  switch (kind) {
    case "warren": {
      // Treillis Warren 24 m — 4 panneaux de 6 m, h = 3 m.
      const nodes = [
        node(1, 0, 0, 0),
        node(2, 6, 0, 0),
        node(3, 12, 0, 0),
        node(4, 18, 0, 0),
        node(5, 24, 0, 0),
        node(6, 3, 0, 3),
        node(7, 9, 0, 3),
        node(8, 15, 0, 3),
        node(9, 21, 0, 3),
      ];
      const beams = [
        beam(1, 1, 6),
        beam(2, 6, 2),
        beam(3, 2, 7),
        beam(4, 7, 3),
        beam(5, 3, 8),
        beam(6, 8, 4),
        beam(7, 4, 9),
        beam(8, 9, 5),
        beam(9, 6, 7),
        beam(10, 7, 8),
        beam(11, 8, 9),
      ];
      return {
        ...base,
        name: "Treillis Warren 24 m",
        structure: {
          ...base.structure,
          nodes,
          beams,
          supports: [
            support(1, [true, true, true, true, true, true]),
            support(5, [false, false, true, false, false, false]),
          ],
          loads: [load(7, -30000), load(8, -30000)],
        },
      };
    }
    case "portique": {
      // Portique industriel — travée 12 m, hauteur 5 m.
      return {
        ...base,
        name: "Portique industriel",
        structure: {
          ...base.structure,
          nodes: [node(1, 0, 0, 0), node(2, 12, 0, 0), node(3, 12, 0, 5), node(4, 0, 0, 5)],
          beams: [beam(1, 1, 4), beam(2, 4, 3), beam(3, 3, 2)],
          supports: [
            support(1, [true, true, true, true, true, true]),
            support(2, [false, false, true, false, false, false]),
          ],
          loads: [load(3, -40000)],
        },
      };
    }
    case "potence": {
      // Potence encastrée — 3 m.
      return {
        ...base,
        name: "Potence encastrée",
        structure: {
          ...base.structure,
          nodes: [node(1, 0, 0, 0), node(2, 3, 0, 0)],
          beams: [beam(1, 1, 2)],
          supports: [support(1, [true, true, true, true, true, true])],
          loads: [load(2, -15000)],
        },
      };
    }
    default: {
      // Poutre continue — 3 travées de 6 m.
      return {
        ...base,
        name: "Poutre continue 3×6 m",
        structure: {
          ...base.structure,
          nodes: [node(1, 0, 0, 0), node(2, 6, 0, 0), node(3, 12, 0, 0), node(4, 18, 0, 0)],
          beams: [beam(1, 1, 2), beam(2, 2, 3), beam(3, 3, 4)],
          supports: [
            support(1, [true, true, true, true, true, true]),
            support(2, [false, false, true, false, false, false]),
            support(3, [false, false, true, false, false, false]),
            support(4, [false, false, true, false, false, false]),
          ],
          loads: [load(2, -20000), load(3, -20000)],
        },
      };
    }
  }
}

import { ENGINEERING_TEMPLATES } from "../lib/engineeringTemplates";

/** v1.6.0 parametric templates (Rust-generated). */
const PARAMETRIC_TEMPLATES = [
  { kind: "warren", label: "Treillis Warren 24 m" },
  { kind: "portique", label: "Portique industriel" },
  { kind: "potence", label: "Potence encastrée" },
  { kind: "continue", label: "Poutre continue" },
];

export function ProjectGalleryModal({
  open,
  onClose,
  onImportFile,
}: {
  open: boolean;
  onClose: () => void;
  /** v1.4.0: direct import surface (.rdm model or CAD wireframe). */
  onImportFile?: (file: File) => void;
}) {
  const loadProject = useProjectStore((s) => s.loadProject);
  const project = useProjectStore((s) => s.project);
  const [entries, setEntries] = useState<GalleryEntry[]>([]);
  // v1.6.0: parametric configurator state (Portée L, Hauteur H, Travées).
  const [paramTemplate, setParamTemplate] =
    useState<ParametricParamsInput["template"]>("WarrenTruss");
  const [paramSpan, setParamSpan] = useState<number | null>(24);
  const [paramHeight, setParamHeight] = useState<number | null>(3);
  const [paramBays, setParamBays] = useState<number | null>(4);
  const [paramSection, setParamSection] = useState("IPE 200");
  const [paramSecondary, setParamSecondary] = useState("IPE 140");
  const [paramBusy, setParamBusy] = useState(false);
  useEffect(() => {
    if (!open) return;
    void get<GalleryEntry[]>(GALLERY_KEY).then((list) => setEntries(list ?? []));
  }, [open]);
  if (!open) return null;

  /** v1.6.0: generate through the pure-Rust parametric engine. */
  const generateParametric = () => {
    setParamBusy(true);
    const params: ParametricParamsInput = {
      template: paramTemplate,
      span_m: paramSpan ?? 24,
      height_m: paramHeight ?? 3,
      bays: paramBays ?? 4,
      primary_section: paramSection,
      secondary_section: paramSecondary,
      material_id: "S235JR",
    };
    const labels: Record<ParametricParamsInput["template"], string> = {
      WarrenTruss: "Treillis Warren",
      PortalFrame: "Portique",
      Cantilever: "Potence",
      ContinuousBeam: "Poutre continue",
    };
    void feaClient
      .generateParametricStructure(params, `${labels[paramTemplate]} ${params.span_m} m`)
      .then((json) => {
        const generated = JSON.parse(json) as ProjectData;
        loadProject(generated);
        toast(t`Structure paramétrique générée`, {
          description: t`${generated.structure.nodes.length} nœuds · ${generated.structure.beams.length} poutres (moteur Rust rdm-cad).`,
        });
        onClose();
      })
      .catch((fault: { message?: string }) => {
        toast.error(t`Génération impossible : ${fault.message ?? "paramètres invalides"}`);
      })
      .finally(() => setParamBusy(false));
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-ink-primary/20 p-4"
      onClick={onClose}
    >
      <div
        className="max-h-[90dvh] w-full max-w-lg overflow-auto rounded-lg border border-hairline bg-panel shadow-[0_8px_24px_rgba(15,23,42,0.08)]"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="border-b border-hairline p-3">
          <h2 className="text-[15px] font-semibold">Projets</h2>
        </div>
        <div className="p-3">
          {/* v1.6.0: parametric configurator (moteur Rust rdm-cad). */}
          <div
            className="rounded border border-accent-ring bg-accent-tint/60 p-2"
            data-testid="parametric-configurator"
          >
            <h3 className="flex items-center gap-1.5 text-[12px] font-semibold text-accent">
              <Trans>Générateur paramétrique (Rust)</Trans>
            </h3>
            <div className="mt-2 grid grid-cols-[92px_1fr] items-center gap-x-2 gap-y-1.5">
              <label className="text-[11px] text-ink-secondary" htmlFor="param-template">
                <Trans>Gabarit</Trans>
              </label>
              <select
                id="param-template"
                className="h-7 w-full rounded border border-hairline bg-panel px-1 text-[12px]"
                value={paramTemplate}
                onChange={(e) =>
                  setParamTemplate(e.currentTarget.value as ParametricParamsInput["template"])
                }
              >
                <option value="WarrenTruss">Treillis Warren</option>
                <option value="PortalFrame">Portique</option>
                <option value="Cantilever">Potence (cantilever)</option>
                <option value="ContinuousBeam">Poutre continue multi-travées</option>
              </select>
              <label className="text-[11px] text-ink-secondary" htmlFor="param-span">
                <Trans>Portée L (m)</Trans>
              </label>
              <NumberFieldRoot
                value={paramSpan}
                min={0.5}
                step={0.5}
                onValueChange={(v) => setParamSpan(v)}
              >
                <NumberFieldInput
                  id="param-span"
                  className="font-data h-7 w-full px-1 text-[12px]"
                />
              </NumberFieldRoot>
              <label className="text-[11px] text-ink-secondary" htmlFor="param-height">
                <Trans>Hauteur H (m)</Trans>
              </label>
              <NumberFieldRoot
                value={paramHeight}
                min={0}
                step={0.25}
                onValueChange={(v) => setParamHeight(v)}
              >
                <NumberFieldInput
                  id="param-height"
                  className="font-data h-7 w-full px-1 text-[12px]"
                />
              </NumberFieldRoot>
              <label className="text-[11px] text-ink-secondary" htmlFor="param-bays">
                <Trans>Travées / panneaux</Trans>
              </label>
              <NumberFieldRoot
                value={paramBays}
                min={1}
                max={24}
                step={1}
                onValueChange={(v) => setParamBays(v)}
              >
                <NumberFieldInput
                  id="param-bays"
                  className="font-data h-7 w-full px-1 text-[12px]"
                />
              </NumberFieldRoot>
              <label className="text-[11px] text-ink-secondary" htmlFor="param-primary">
                <Trans>Profilé principal</Trans>
              </label>
              <select
                id="param-primary"
                className="font-data h-7 w-full rounded border border-hairline bg-panel px-1 text-[12px]"
                value={paramSection}
                onChange={(e) => setParamSection(e.currentTarget.value)}
              >
                {["IPE 140", "IPE 200", "IPE 240", "IPE 300", "HEA 180", "HEA 200", "HEA 240"].map(
                  (d) => (
                    <option key={d} value={d}>
                      {d}
                    </option>
                  ),
                )}
              </select>
              <label className="text-[11px] text-ink-secondary" htmlFor="param-secondary">
                <Trans>Profilé secondaire</Trans>
              </label>
              <select
                id="param-secondary"
                className="font-data h-7 w-full rounded border border-hairline bg-panel px-1 text-[12px]"
                value={paramSecondary}
                onChange={(e) => setParamSecondary(e.currentTarget.value)}
              >
                {["IPE 140", "IPE 160", "IPE 200", "CHS 114.3x6", "RHS 120x80x6"].map((d) => (
                  <option key={d} value={d}>
                    {d}
                  </option>
                ))}
              </select>
            </div>
            <button
              type="button"
              className="mt-2 w-full rounded bg-accent px-2 py-1.5 text-[12px] text-white disabled:opacity-50"
              data-testid="generate-parametric"
              disabled={paramBusy}
              onClick={generateParametric}
            >
              {paramBusy ? <Trans>Génération…</Trans> : <Trans>Générer la structure</Trans>}
            </button>
          </div>
          <div className="mt-3 flex items-center justify-between">
            <h3 className="text-[12px] text-ink-secondary">
              <Trans>Modèles types</Trans>
            </h3>
            {/* v1.4.0: fresh 0-node project. */}
            <button
              type="button"
              className="rounded border border-hairline px-2 py-0.5 text-[11px] text-ink-secondary hover:border-accent hover:text-accent"
              data-testid="new-blank-project"
              onClick={() => {
                loadProject({
                  version: 1,
                  name: "Nouveau projet",
                  structure: {
                    nodes: [],
                    beams: [],
                    supports: [],
                    loads: [],
                    sections: {},
                    materials: {},
                    self_weight_enabled: false,
                  },
                });
                onClose();
              }}
            >
              <Trans>+ Nouveau projet vierge</Trans>
            </button>
          </div>
          <div className="mt-2 grid grid-cols-2 gap-2">
            {PARAMETRIC_TEMPLATES.map((t) => {
              // v1.4.0: rich metadata cards (node/beam counts, span, tags).
              const preview = buildTemplate(t.kind);
              const nodeCount = preview.structure.nodes.length;
              const beamCount = preview.structure.beams.length;
              const xs = preview.structure.nodes.map((n) => n.x);
              const zs = preview.structure.nodes.map((n) => n.z);
              const span = xs.length > 0 ? Math.max(...xs) - Math.min(...xs) : 0;
              const height = zs.length > 0 ? Math.max(...zs) - Math.min(...zs) : 0;
              return (
                <button
                  key={t.kind}
                  type="button"
                  className="rounded border border-hairline p-2 text-left text-[12px] hover:border-accent hover:bg-accent-tint"
                  data-testid={`gallery-${t.kind}`}
                  onClick={() => {
                    loadProject(preview);
                    onClose();
                  }}
                >
                  <span className="font-medium text-ink-primary">{t.label}</span>
                  <span className="font-data mt-1 block text-[11px] text-ink-muted">
                    {nodeCount} nœuds · {beamCount} poutres · portée {span.toFixed(0)} m
                    {height > 0 ? ` · h ${height.toFixed(1)} m` : ""}
                  </span>
                  <span className="mt-1 block text-[11px] text-accent">EN 1993 · S235JR</span>
                </button>
              );
            })}
            {/* v2.0.0: the 12 validated engineering templates with "Pourquoi ce modèle" notes. */}
            {ENGINEERING_TEMPLATES.map((template) => (
              <div
                key={template.id}
                className="rounded-lg border border-slate-200 p-3 dark:border-slate-700"
              >
                <p className="text-sm font-semibold">{template.name}</p>
                <p className="mt-1 text-xs italic text-slate-600 dark:text-slate-300">
                  « Pourquoi ce modèle » — {template.why}
                </p>
                <button
                  type="button"
                  onClick={() => {
                    const structure = {
                      nodes: template.nodes,
                      beams: template.beams.map((beam) => ({
                        ...beam,
                        roll_angle_rad: 0,
                        releases_start: [false, false, false, false, false, false],
                        releases_end: [false, false, false, false, false, false],
                        k_buckling_y: 1.0,
                        k_buckling_z: 1.0,
                      })),
                      supports: [],
                      loads: template.loads.map((load) => ({
                        case: load.case,
                        kind: load.kind,
                        beam_id: load.beam_id ?? 0,
                        node_id: load.node_id ?? 0,
                        position_ratio: load.position_ratio ?? 0.5,
                        q_start: load.q_start ?? 0,
                        q_end: load.q_end ?? 0,
                        forces: { fx: 0, fy: 0, fz: load.fz ?? 0, mx: 0, my: 0, mz: 0 },
                        direction: load.direction ?? { x: 0, y: -1, z: 0 },
                      })),
                      sections: {},
                      materials: {},
                      self_weight_enabled: false,
                    };
                    loadProject({ version: 2, name: template.name, structure });
                  }}
                  className="mt-2 w-full rounded bg-blue-600 py-1 text-xs font-semibold text-white"
                >
                  Charger
                </button>
              </div>
            ))}
          </div>
          {/* v1.4.0: direct file import (.rdm / CAD). */}
          <label className="mt-3 inline-flex cursor-pointer items-center gap-1 rounded border border-hairline px-2 py-1 text-[11px] text-ink-secondary hover:border-accent hover:text-accent">
            Importer (.rdm, .dxf, .step, .igs)
            <input
              type="file"
              accept=".rdm,.dxf,.step,.stp,.igs,.iges"
              className="hidden"
              onChange={(e) => {
                const file = e.currentTarget.files?.[0];
                if (file !== undefined) {
                  onImportFile?.(file);
                  onClose();
                }
                e.currentTarget.value = "";
              }}
            />
          </label>
          <h3 className="mt-4 text-[12px] text-ink-secondary">Enregistrés en local</h3>
          {entries.length === 0 ? (
            <p className="mt-1 text-[12px] text-ink-muted">Aucun projet enregistré.</p>
          ) : (
            <ul className="mt-1 max-h-40 overflow-auto">
              {entries.map((e) => (
                <li key={e.id}>
                  <button
                    type="button"
                    className="w-full rounded px-2 py-1.5 text-left text-[13px] hover:bg-accent-tint"
                    onClick={() => {
                      loadProject(e.project);
                      onClose();
                    }}
                  >
                    <span className="font-data">{e.name}</span>
                    <span className="ml-2 text-[11px] text-ink-muted">
                      {new Date(e.savedAt).toLocaleString("fr-FR")}
                    </span>
                  </button>
                </li>
              ))}
            </ul>
          )}
        </div>
        <div className="flex gap-2 border-t border-hairline p-3">
          <button
            type="button"
            className="flex-1 rounded border border-hairline px-2 py-1.5 text-[13px] text-ink-secondary"
            onClick={() => {
              void saveToGallery(useProjectStore.getState().project);
              onClose();
            }}
          >
            <Trans>Enregistrer le projet courant</Trans>
          </button>
          {/* v1.6.0: header project menu `Exporter (.rdm)` surface. */}
          <button
            type="button"
            className="flex-1 rounded border border-accent px-2 py-1.5 text-[13px] text-accent hover:bg-accent-tint"
            data-testid="gallery-export-rdm"
            onClick={() => {
              downloadText(
                `${project.name.replace(/[^\w-]+/g, "_")}.rdm`,
                JSON.stringify(project, null, 2),
                "application/json;charset=utf-8",
              );
              toast(t`Modèle .rdm exporté`);
              onClose();
            }}
          >
            <Trans>Exporter (.rdm)</Trans>
          </button>
        </div>
      </div>
    </div>
  );
}
